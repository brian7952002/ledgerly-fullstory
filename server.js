// Ledgerly demo server.
// - Serves the marketing site + product (public/)
// - Injects the official Fullstory snippet with your org ID
// - Mocks three "other systems": the experimentation platform, the CRM, and billing
import express from 'express';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { generateSnippetText } from '@fullstory/snippet';
import { runBillingCycle } from './lib/billing.js';
import { fsServerEnabled } from './lib/fs-server.js';

const PORT = process.env.PORT || 3000;
const ORG_ID = process.env.FS_ORG_ID;
const DB_FILE = path.resolve('data/db.json');

// ---- tiny JSON "database" standing in for the CRM + experiment platform ----
const emptyDb = () => ({ exposures: {}, users: [] });
const loadDb = () => (fs.existsSync(DB_FILE) ? JSON.parse(fs.readFileSync(DB_FILE, 'utf8')) : emptyDb());
const saveDb = (db) => {
  fs.mkdirSync(path.dirname(DB_FILE), { recursive: true });
  fs.writeFileSync(DB_FILE, JSON.stringify(db, null, 2));
};

const app = express();
app.use(express.json());

// Official snippet, generated by Fullstory's own @fullstory/snippet package.
app.get('/js/fs-snippet.js', (_req, res) => {
  res.type('application/javascript');
  if (!ORG_ID) {
    return res.send("console.warn('[Ledgerly] FS_ORG_ID not set - Fullstory capture is OFF (calls are still logged).');");
  }
  res.send(generateSnippetText({ orgId: ORG_ID }));
});

app.use(express.static('public', { extensions: ['html'] }));

// ---- Mock experimentation platform: records exposures (it only sees top-of-funnel) ----
app.post('/api/exposure', (req, res) => {
  const { anon_id, experiment_key, variant } = req.body;
  const db = loadDb();
  db.exposures[anon_id] = { experiment_key, variant, at: new Date().toISOString() };
  saveDb(db);
  res.json({ ok: true });
});

// ---- Mock CRM: account creation returns our internal user id (the Fullstory uid) ----
app.post('/api/signup', (req, res) => {
  const { anon_id, acq_campaign, acq_source, variant, billing_period, wanted_monthly } = req.body;
  const uid = 'usr_' + crypto.randomBytes(4).toString('hex');
  const db = loadDb();
  db.users.push({
    uid, anon_id, acq_campaign, acq_source, variant, billing_period, wanted_monthly: !!wanted_monthly,
    plan: 'trial', invoices_sent: 0, signed_up_at: new Date().toISOString(),
  });
  saveDb(db);
  res.json({ uid });
});

app.post('/api/activity', (req, res) => {
  const db = loadDb();
  const user = db.users.find((u) => u.uid === req.body.uid);
  if (user) user.invoices_sent += 1;
  saveDb(db);
  res.json({ ok: !!user });
});

// What the A/B tool reports: exposures -> signups. No revenue, no behavior.
app.get('/api/experiment/readout', (_req, res) => {
  const db = loadDb();
  const rows = {};
  for (const { variant } of Object.values(db.exposures)) {
    rows[variant] ??= { variant, exposures: 0, signups: 0 };
    rows[variant].exposures += 1;
  }
  for (const u of db.users) if (rows[u.variant]) rows[u.variant].signups += 1;
  const out = Object.values(rows).map((r) => ({ ...r, signup_rate: r.exposures ? r.signups / r.exposures : 0 }));
  res.json({ experiment_key: 'pricing_page_v2', primary_metric: 'signup_rate', rows: out });
});

// Mock billing: trial ends -> converts or expires -> pushed to Fullstory via Server API
app.post('/api/billing/run', async (_req, res) => {
  const db = loadDb();
  const log = await runBillingCycle(db.users);
  saveDb(db);
  res.json({ fullstory_server_api: fsServerEnabled() ? 'live' : 'dry-run (no FS_API_KEY)', log });
});

// The GitHub Pages copy of the site has no backend. When the simulator drives it, it reports
// each visitor here so the local billing cycle can still push outcomes to Fullstory.
app.post('/api/import', (req, res) => {
  const { exposure, user } = req.body;
  const db = loadDb();
  if (exposure) db.exposures[exposure.anon_id] = { experiment_key: 'pricing_page_v2', variant: exposure.variant, at: new Date().toISOString() };
  if (user) db.users.push({ ...user, plan: 'trial', signed_up_at: new Date().toISOString() });
  saveDb(db);
  res.json({ ok: true });
});

app.post('/api/reset', (_req, res) => {
  saveDb(emptyDb());
  res.json({ ok: true });
});

app.listen(PORT, () => {
  console.log(`Ledgerly running at http://localhost:${PORT}`);
  console.log(`  Fullstory capture: ${ORG_ID ? 'ON (org ' + ORG_ID + ')' : 'OFF - set FS_ORG_ID in .env'}`);
  if (!ORG_ID) console.warn('  !! Sessions are NOT being recorded. Do not run the simulator for the demo until FS_ORG_ID is set.');
  console.log(`  Fullstory Server API: ${fsServerEnabled() ? 'live' : 'dry-run - set FS_API_KEY in .env'}`);
});
